from app.orchestration.checkpointer import build_in_memory_checkpointer
from app.reporting import report_renderer, report_service


@pytest.fixture
def ledger(tmp_path):
    return shadow.ShadowLedger(tmp_path / "ledger.json")


# --- normalize_mode: fail-safe ----------------------------------------


@pytest.mark.parametrize(
    "value, expected",
    [("live", "live"), ("LIVE", "live"), (" Live ", "live"),
     ("shadow", "shadow"), ("", "shadow"), (None, "shadow"), ("garbage", "shadow")],
)
def test_normalize_mode_only_accepts_an_explicit_live(value, expected):
    assert shadow.normalize_mode(value) == expected


# --- ShadowLedger ------------------------------------------------


def test_a_fresh_engagement_is_locked(ledger):
    assert ledger.is_client_delivery_unlocked() is False
    assert ledger.status()["shadow_runs"] == []


def test_recording_a_shadow_run_does_not_by_itself_unlock(ledger):
    ledger.record_shadow_run("run-1", application_count=100)
    assert ledger.is_client_delivery_unlocked() is False
    assert [r["run_id"] for r in ledger.status()["shadow_runs"]] == ["run-1"]


def test_record_shadow_run_is_idempotent_by_run_id(ledger):
    ledger.record_shadow_run("run-1", application_count=100)
    ledger.record_shadow_run("run-1", application_count=100)
    assert len(ledger.status()["shadow_runs"]) == 1


def test_signing_off_a_run_that_never_ran_as_shadow_is_rejected(ledger):
    with pytest.raises(shadow.ShadowSignoffError):
        ledger.sign_off("run-unknown", reviewer="internal", decision="approved")


def test_an_approved_signoff_of_a_completed_shadow_run_unlocks_delivery(ledger):
    ledger.record_shadow_run("run-1", application_count=100)
    ledger.sign_off("run-1", reviewer="internal-reviewer", decision="approved")
    assert ledger.is_client_delivery_unlocked() is True


def test_a_rejected_signoff_is_recorded_but_leaves_the_engagement_locked(ledger):
    ledger.record_shadow_run("run-1", application_count=100)
    record = ledger.sign_off("run-1", reviewer="internal", decision={"action": "reject", "reason": "numbers off"})
    assert record["approved"] is False
    assert ledger.is_client_delivery_unlocked() is False


def test_the_ledger_persists_across_instances(ledger):
    ledger.record_shadow_run("run-1", application_count=1)
    ledger.sign_off("run-1", reviewer="internal", decision="approved")
    reopened = shadow.ShadowLedger(ledger.path)
    assert reopened.is_client_delivery_unlocked() is True


# --- delivery_status ------------------------------------------


def test_a_shadow_run_is_never_deliverable(ledger):
    verdict = ledger.delivery_status("shadow")
    assert verdict["run_mode"] == "shadow"
    assert verdict["client_deliverable"] is False
    assert "section 2" in verdict["reason"]


def test_a_live_run_is_blocked_until_the_engagement_is_unlocked(ledger):
    assert ledger.delivery_status("live")["client_deliverable"] is False
    ledger.record_shadow_run("run-1", application_count=1)
    ledger.sign_off("run-1", reviewer="internal", decision="approved")
    unlocked = ledger.delivery_status("live")
    assert unlocked["client_deliverable"] is True
    assert unlocked["shadow_signoff_on_record"] is True


# --- report stamp + renderer banner --------------------------


def _state(run_mode="shadow"):
    return {"run_id": "r1", "data_sensitivity": "synthetic", "run_mode": run_mode, "kernel_results": {}}


def test_build_report_without_a_delivery_verdict_stamps_not_deliverable():
    report = report_service.build_report(_state())
    assert report["run_mode"] == "shadow"
    assert report["delivery"]["client_deliverable"] is False


def test_build_report_carries_the_supplied_delivery_verdict(ledger):
    ledger.record_shadow_run("prior", application_count=1)
    ledger.sign_off("prior", reviewer="internal", decision="approved")
    report = report_service.build_report(_state("live"), delivery=ledger.delivery_status("live"))
    assert report["delivery"]["client_deliverable"] is True


def test_the_renderer_banners_a_shadow_report():
    md = report_renderer.render_markdown(report_service.build_report(_state("shadow")))
    assert "> **SHADOW RUN -- INTERNAL REVIEW ONLY.**" in md
    assert md.startswith("# APR Portfolio Rationalization Report")
    assert "- Mode: shadow" in md


def test_the_renderer_banners_a_blocked_live_report(ledger):
    report = report_service.build_report(_state("live"), delivery=ledger.delivery_status("live"))
    md = report_renderer.render_markdown(report)
    assert "> **NOT CLIENT-DELIVERABLE.**" in md


def test_the_renderer_omits_the_banner_when_delivery_is_unlocked(ledger):
    ledger.record_shadow_run("prior", application_count=1)
    ledger.sign_off("prior", reviewer="internal", decision="approved")
    report = report_service.build_report(_state("live"), delivery=ledger.delivery_status("live"))
    md = report_renderer.render_markdown(report)
    assert "INTERNAL REVIEW ONLY" not in md and "NOT CLIENT-DELIVERABLE" not in md


# --- render_report node wiring (real graph, empty portfolio) -------


def _runner(monkeypatch, tmp_path):
    led = shadow.ShadowLedger(tmp_path / "ledger.json")
    monkeypatch.setattr(nodes.shadow, "default_ledger", lambda: led)
    runner = BatchRunner(checkpointer=build_in_memory_checkpointer(), submit_fn=lambda fn: fn())
    return runner, led


def test_a_shadow_run_records_itself_and_ships_a_non_deliverable_report(monkeypatch, tmp_path):
    runner, led = _runner(monkeypatch, tmp_path)
    run_id = runner.submit([], data_sensitivity="synthetic", run_mode="shadow")
    runner.resume(run_id, "approved")

    view = runner.get(run_id)
    assert view["run_mode"] == "shadow"
    assert view["delivery"]["client_deliverable"] is False
    assert [r["run_id"] for r in led.status()["shadow_runs"]] == [run_id]


def test_a_live_run_becomes_deliverable_only_after_the_shadow_run_is_signed_off(monkeypatch, tmp_path):
    runner, led = _runner(monkeypatch, tmp_path)

    shadow_id = runner.submit([], data_sensitivity="synthetic", run_mode="shadow")
    runner.resume(shadow_id, "approved")

    live_before = runner.submit([], data_sensitivity="synthetic", run_mode="live")
    runner.resume(live_before, "approved")
    assert runner.get(live_before)["delivery"]["client_deliverable"] is False

    led.sign_off(shadow_id, reviewer="internal-reviewer", decision="approved")

    live_after = runner.submit([], data_sensitivity="synthetic", run_mode="live")
    runner.resume(live_after, "approved")
    assert runner.get(live_after)["delivery"]["client_deliverable"] is True


# --- HTTP surface -------------------------------------------


@pytest.fixture
def client():
    runner = BatchRunner(checkpointer=build_in_memory_checkpointer(), submit_fn=lambda fn: fn())
    app = FastAPI()
    app.include_router(batch_api.router)
    app.include_router(shadow_api.router)
    app.dependency_overrides[batch_api._runner_dep] = lambda: runner
    with TestClient(app) as c:
        yield c


def _run(client, run_mode="shadow"):
    """Submit an empty (hermetic) run and clear gate 1, returning the
    completed run view."""
    run_id = client.post(
        "/api/runs", json={"applications": [], "data_sensitivity": "synthetic", "run_mode": run_mode}
    ).json()["run_id"]
    return client.post(f"/api/runs/{run_id}/resume", json={"decision": "approved"}).json()


def test_submit_defaults_to_shadow_and_reports_a_non_deliverable_result(client):
    body = _run(client)
    assert body["status"] == "complete"
    assert body["run_mode"] == "shadow"
    assert body["delivery"]["client_deliverable"] is False


def test_an_unrecognized_run_mode_is_422(client):
    assert client.post("/api/runs", json={"applications": [], "run_mode": "leaky"}).status_code == 422


def test_shadow_status_starts_locked_then_unlocks_after_signoff(client):
    assert client.get("/api/shadow").json()["client_delivery_unlocked"] is False

    run_id = _run(client, "shadow")["run_id"]
    resp = client.post("/api/shadow/signoff", json={"run_id": run_id, "reviewer": "internal", "decision": "approved"})
    assert resp.status_code == 200
    assert resp.json()["client_delivery_unlocked"] is True
    assert client.get("/api/shadow").json()["client_delivery_unlocked"] is True


def test_a_live_run_after_signoff_is_client_deliverable(client):
    shadow_id = _run(client, "shadow")["run_id"]
    client.post("/api/shadow/signoff", json={"run_id": shadow_id, "reviewer": "internal", "decision": "approved"})

    live = _run(client, "live")
    assert live["delivery"]["client_deliverable"] is True


def test_signing_off_an_unknown_run_is_404(client):
    resp = client.post("/api/shadow/signoff", json={"run_id": "nope", "reviewer": "internal", "decision": "approved"})
    assert resp.status_code == 404
