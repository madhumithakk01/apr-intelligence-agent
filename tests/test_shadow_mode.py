"""Shadow-mode delivery gate -- CLAUDE.md section 2.

Nothing generated by the pipeline is client-deliverable until a full
shadow run has completed and been signed off. These tests cover the
ledger, the delivery verdict, the report stamp and banner, the
render_report wiring, and the HTTP surface.
"""

